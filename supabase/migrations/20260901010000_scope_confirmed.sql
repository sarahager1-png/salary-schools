-- "תמיד כותב 100 אחוז"
--
-- scope_pct הוא NOT NULL DEFAULT 100. מנהלת שממלאת את הטבלה מזינה שם,
-- ת.ז., שעות ודרגה — לא אחוז משרה; האחוז נקבע אצל שרה, ביד, אחרי
-- שהשורות מגיעות. עד אז העמודה מראה 100 בדיוק כמו שורה שבאמת במשרה
-- מלאה, ואין דרך להבדיל. רעננה, גני תקוה, רמת ישי ואור עקיבא — 42
-- שורות, כולן "100%", אף אחת מהן לא נקבעה.
--
-- 100 שלא נבחר נכנס לחישוב כאילו נבחר: הבראה וביגוד יחסיים לאחוז,
-- והסימולציה עצמה רצה עליו. לכן כאן חותמת ולא דגל — מתי האחוז נקבע,
-- ועל ידי מי שנכנס לשדה. ריק = טרם נקבע.
--
-- השורות הקיימות אינן נגעות. אחוז שאינו 100 הוקלד ביד — אין דרך אחרת
-- שהוא הגיע לשם — ולכן האפליקציה סופרת גם אותו כנקבע, בלי לכתוב דבר
-- למסד. מי שיושבת על 100 חוזרת לשלב הראשון, וזה בדיוק מה שהתבקש.
alter table public.teacher_months
  add column if not exists scope_set_at timestamptz;

comment on column public.teacher_months.scope_set_at is
  'מתי אחוז המשרה נקבע ביד. ריק = עדיין ברירת המחדל, טרם נקבע.';

notify pgrst, 'reload schema';
